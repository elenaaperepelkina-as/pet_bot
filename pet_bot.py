user_data = {}

# --- Кнопки ---
next_button = types.KeyboardButton("Далее")
ok_button = types.KeyboardButton("Да")
not_ok_button = types.KeyboardButton("Нет")


def send_task(chat_id, creature_name, task_name):
    """Отправляет задание пользователю."""
    task = creatures_db[creature_name][task_name]
    user_data[chat_id] = {
        "creature": creature_name,
        "task": task_name,
    }

    # Отправляем задание
    keyboard = types.ReplyKeyboardMarkup(resize_keyboard=True)
    keyboard.add(next_button)
    bot.send_message(chat_id, task["task"], reply_markup=keyboard)

    # Дополнительное сообщение
    if "additional_message" in task:
        bot.send_message(chat_id, task["additional_message"])


